import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
test("resizing a moving window cancels momentum and bounce before taking control", () => {
  const source = readFileSync(new URL("../js/main.js", import.meta.url), "utf8");
  const classes = () => { const set = new Set(); return { add: (name) => set.add(name), remove: (name) => set.delete(name), contains: (name) => set.has(name) }; };
  const handlers = new Map();
  const frames = new Map(); let nextFrame = 0; let saved = 0; let captured = false; let bounced = false;
  const grip = { dataset: { grip: "se" }, addEventListener: (type, fn) => handlers.set(type, fn), removeEventListener: (type) => handlers.delete(type), setPointerCapture: () => { captured = true; }, hasPointerCapture: () => captured, releasePointerCapture: () => { captured = false; } };
  const style = { left: "40px", top: "50px", width: "320px", height: "240px" };
  Object.defineProperty(style, "cssText", { get() { return Object.entries(this).map(([name, value]) => name + ":" + value).join(";"); }, set(text) { for (const match of text.matchAll(/(left|top|width|height):(-?\d+)px/g)) this[match[1]] = match[2] + "px"; } });
  const node = { style, dataset: { appId: "notes" }, isConnected: true, classList: classes(), querySelectorAll: () => [grip], animate: () => ({ cancel: () => { bounced = true; } }) };
  for (const [property, key] of [["offsetLeft", "left"], ["offsetTop", "top"], ["offsetWidth", "width"], ["offsetHeight", "height"]]) Object.defineProperty(node, property, { get: () => parseInt(style[key], 10) });
  const desk = { classList: classes() };
  const context = vm.createContext({ performance: { now: () => 0 }, wins: { clientWidth: 1000, clientHeight: 800 }, desk, document: { body: { dataset: {} } }, getComputedStyle: () => ({ minWidth: "200px", minHeight: "150px" }), focusWin() {}, playSound() {}, toScene: (x, y) => [x, y], rememberWindows: () => { saved += 1; }, requestAnimationFrame: (callback) => { frames.set(++nextFrame, callback); return nextFrame; }, cancelAnimationFrame: (id) => frames.delete(id) });
  const start = source.includes("const windowImpacts =") ? source.indexOf("const windowImpacts =") : source.indexOf("function impact(");
  vm.runInContext(source.slice(start, source.indexOf("function drag(node)")), context);
  const flush = () => { const pending = [...frames]; frames.clear(); pending.forEach(([, callback]) => callback(16)); };
  context.flingWindow(node, 3, 2);
  flush();
  assert.equal(node.offsetLeft, 88);
  assert.equal(node.offsetTop, 82);
  context.impact(node, 1, "left center", true);
  context.resizeGrip(node);
  handlers.get("pointerdown")({ button: 0, pointerId: 7, clientX: 400, clientY: 200, preventDefault() {}, stopPropagation() {} });
  assert.equal(node.dataset.flinging, undefined);
  assert.ok(bounced, "the collision transform must stop before resizing");
  handlers.get("pointermove")({ pointerId: 7, clientX: 437, clientY: 235 });
  flush();
  assert.equal(node.offsetLeft, 88);
  assert.equal(node.offsetTop, 82);
  assert.equal(node.offsetWidth, 357);
  assert.equal(node.offsetHeight, 275);
  assert.equal(frames.size, 0, "the canceled momentum frame must not schedule another frame");
  handlers.get("pointerup")({ pointerId: 7 });
  assert.equal(saved, 1);
  assert.equal(captured, false);
  assert.equal(handlers.has("pointermove"), false);
});

